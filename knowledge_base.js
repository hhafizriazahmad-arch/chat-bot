// Sync live catalog from tsgolf.co.uk/products.json if available
export async function getLiveCatalog() {
  try {
    const res = await fetch("https://tsgolf.co.uk/products.json?limit=250");
    if (res.ok) {
      const data = await res.json();
      if (data.products && data.products.length > 0) {
        return data.products;
      }
    }
  } catch (e) {
    console.warn("Live catalog sync fallback to internal index:", e.message);
  }
  return TS_GOLF_KNOWLEDGE.products;
}
